//! The app's icon vocabulary: each variant is the lucide icon React SONE uses in that spot
//! (see `icons.rs`). Play, pause and skip are filled, as React passes `fill="currentColor"`.

use rune::{Color, El};

use crate::icons as i;

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum G {
    // transport
    Play,
    Pause,
    Next,
    Prev,
    Shuffle,
    Repeat,
    // hearts and lists
    Heart,
    HeartFilled,
    List,
    ListPlus,
    ListEnd,
    Plus,
    More,
    // window, navigation, chrome
    Close,
    Minus,
    Square,
    Back,
    Forward,
    ChevronDown,
    ChevronUp,
    ChevronRight,
    Search,
    Home,
    Compass,
    Bell,
    Library,
    User,
    Music,
    // player bar
    VolumeX,
    Volume1,
    Speaker,
    Mic,
    PopOut,
    Maximize,
    Minimize,
    // actions
    Share,
    Link,
    Pencil,
    Lock,
    Unlock,
    Check,
    Radio,
    Trash,
    UserPlus,
    UserCheck,
    FolderInput,
    FolderOpen,
    Loader,
    Sparkles,
    Users,
    // account menu
    Headphones,
    Shield,
    Settings,
    Keyboard,
    Info,
    LogOut,
    Clock,
    Sort,
    // sign-in
    External,
}

pub fn lucide(g: G) -> &'static rune::Icon {
    match g {
        G::Play => &i::PLAY_FILLED,
        G::Pause => &i::PAUSE_FILLED,
        G::Next => &i::SKIP_FORWARD_FILLED,
        G::Prev => &i::SKIP_BACK_FILLED,
        G::Shuffle => &i::SHUFFLE,
        G::Repeat => &i::REPEAT,
        G::Heart => &i::HEART,
        G::HeartFilled => &i::HEART_FILLED,
        G::List => &i::LIST_MUSIC,
        G::ListPlus => &i::LIST_PLUS,
        G::ListEnd => &i::LIST_END,
        G::Plus => &i::PLUS,
        G::More => &i::MORE_HORIZONTAL,
        G::Close => &i::X,
        G::Minus => &i::MINUS,
        G::Square => &i::SQUARE,
        G::Back => &i::CHEVRON_LEFT,
        G::Forward => &i::CHEVRON_RIGHT,
        G::ChevronDown => &i::CHEVRON_DOWN,
        G::ChevronUp => &i::CHEVRON_UP,
        G::ChevronRight => &i::CHEVRON_RIGHT,
        G::Search => &i::SEARCH,
        G::Home => &i::HOME,
        G::Compass => &i::COMPASS,
        G::Bell => &i::BELL,
        G::Library => &i::LIBRARY,
        G::User => &i::USER,
        G::Music => &i::MUSIC,
        G::VolumeX => &i::VOLUME_X,
        G::Volume1 => &i::VOLUME_1,
        G::Speaker => &i::VOLUME_2,
        G::Mic => &i::MIC_2,
        G::PopOut => &i::PICTURE_IN_PICTURE_2,
        G::Maximize => &i::MAXIMIZE_2,
        G::Minimize => &i::MINIMIZE_2,
        G::Share => &i::SHARE,
        G::Link => &i::LINK,
        G::Pencil => &i::PENCIL,
        G::Lock => &i::LOCK,
        G::Unlock => &i::UNLOCK,
        G::Check => &i::CHECK,
        G::Radio => &i::RADIO,
        G::Trash => &i::TRASH_2,
        G::UserPlus => &i::USER_PLUS,
        G::UserCheck => &i::USER_CHECK,
        G::FolderInput => &i::FOLDER_INPUT,
        G::FolderOpen => &i::FOLDER_OPEN,
        G::Loader => &i::LOADER_2,
        G::Sparkles => &i::SPARKLES,
        G::Users => &i::USERS,
        G::Headphones => &i::HEADPHONES,
        G::Shield => &i::SHIELD,
        G::Settings => &i::SETTINGS,
        G::Keyboard => &i::KEYBOARD,
        G::Info => &i::INFO,
        G::LogOut => &i::LOG_OUT,
        G::Clock => &i::CLOCK,
        G::Sort => &i::ARROW_UP_DOWN,
        G::External => &i::EXTERNAL_LINK,
    }
}

/// `g` at `size` points, in `c`. Decorative: the button around it carries the name.
pub fn glyph(g: G, size: f32, c: Color) -> El {
    rune::icon(lucide(g), size).color(c).a11y_hidden()
}
